#include "../includes/fractol.h"

void	my_mlx_pixel_put(t_img *data, int x, int y, int color)
{
	int	offset;

	if (x >= 0 && x < WIDTH && y >= 0 && y < HEIGHT)
	{
		offset = (y * data->line_length) + (x * (data->bits_per_pixel / 8));
		*(unsigned int *)(data->addr + offset) = color;
	}
}
